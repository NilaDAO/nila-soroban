#!/usr/bin/env python3
"""Write docs/EVENT_SCHEMA.md from the contracts' #[contractevent] structs (SCF #45 T2 row 27).

    python3 scripts/event-schema.py            # writes docs/EVENT_SCHEMA.md
    python3 scripts/event-schema.py --check    # exit 1 when the file is not current

soroban-sdk's default for `#[contractevent]`: the first topic is the struct name in snake_case, then the `#[topic]`
fields in order; the data is a map of the other fields. Every struct here uses the default (the script refuses any
other form, so the table never guesses).
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "EVENT_SCHEMA.md"
# Source folder → the name the deployment and the indexer (indexer.nila.land) use.
NAMES = {
    "roles": "roles", "land-title": "land_title", "fund-viewer": "fund_viewer", "fund-core": "fund_core",
    "fx-pool": "fx_pool", "machinery": "machinery", "crop-calendar": "crop_calendar", "senior": "senior",
    "deployer": "account_deployer", "account": "member account (one per member)",
    "nila-common": "every upgradeable contract (nila_common::upgrade)",
}
ORDER = list(NAMES)
EVENT = re.compile(r"#\[contractevent(\([^)]*\))?\]")
STRUCT = re.compile(r"pub struct (\w+)\s*\{")
FIELD = re.compile(r"pub (\w+)\s*:\s*([^,]+?),?\s*$")


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def docs_above(lines, i):
    out = []
    j = i - 1
    while j >= 0 and (lines[j].strip().startswith("///") or lines[j].strip().startswith("#[")):
        s = lines[j].strip()
        if s.startswith("///"):
            out.insert(0, s[3:].strip())
        j -= 1
    return " ".join(out)


def parse(path: Path):
    lines = path.read_text().splitlines()
    for i, line in enumerate(lines):
        m = EVENT.search(line)
        if not m:
            continue
        if m.group(1):
            sys.exit(f"{path}:{i + 1}: #[contractevent{m.group(1)}] is not the default form; extend this script")
        k = i + 1
        while not STRUCT.search(lines[k]):
            k += 1
        name = STRUCT.search(lines[k]).group(1)
        doc = docs_above(lines, i)
        topics, data, fdoc, is_topic = [], [], [], False
        k += 1
        while lines[k].strip() != "}":
            s = lines[k].strip()
            if s.startswith("///"):
                fdoc.append(s[3:].strip())
            elif s == "#[topic]":
                is_topic = True
            elif FIELD.match(s):
                f, t = FIELD.match(s).groups()
                (topics if is_topic else data).append((f, t.strip(), " ".join(fdoc)))
                fdoc, is_topic = [], False
            k += 1
        yield {"struct": name, "name": snake(name), "doc": doc, "topics": topics, "data": data, "line": i + 1}


def build() -> str:
    by = {}
    for p in sorted((ROOT / "contracts").glob("*/src/**/*.rs")):
        folder = p.relative_to(ROOT / "contracts").parts[0]
        for e in parse(p):
            e["file"] = p.relative_to(ROOT).as_posix()
            by.setdefault(folder, []).append(e)
    total = sum(len(v) for v in by.values())
    out = [
        "# Event schema",
        "",
        f"Generated by `scripts/event-schema.py` from the `#[contractevent]` structs ({total} events); do not edit by hand.",
        "Every event is kept by the indexer at [indexer.nila.land](https://indexer.nila.land/events) "
        "(nila-sensing `indexer/`), where `name` is the first topic and `contract` the deployed name below.",
        "",
        "**Shape (soroban-sdk default):** topics = `[name, …the topic fields in order]`; data = a map of the data fields.",
        "Amounts (`i128`) are in the asset's units, 7 decimals (`docs/STORAGE_AND_DECIMALS.md`).",
        "",
    ]
    for folder in sorted(by, key=lambda f: ORDER.index(f) if f in ORDER else 99):
        evs = by[folder]
        out += [f"## {NAMES.get(folder, folder)}", "", f"Source: `contracts/{folder}/`.", "",
                "| Event (`name`) | Topics after the name | Data fields | Meaning |", "|---|---|---|---|"]
        for e in sorted(evs, key=lambda e: e["name"]):
            t = "<br>".join(f"`{f}`: {ty}" for f, ty, _ in e["topics"]) or "—"
            d = "<br>".join(f"`{f}`: {ty}" + (f" — {doc}" if doc else "") for f, ty, doc in e["data"]) or "—"
            out.append(f"| `{e['name']}` | {t} | {d} | {e['doc'] or ''} [src]({'../' + e['file']}#L{e['line']}) |"
                       .replace("| [src]", "| [src]"))
        out.append("")
    out += ["## nin_sac (the nIN token)", "",
            "The Stellar Asset Contract of nIN: Stellar's standard token events (CAP-46-6, SEP-41), not Nila code. "
            "Seen on mainnet: `mint`, `transfer`, `set_admin`, `set_authorized`; also possible: `burn`, `clawback`, "
            "`approve`. Topics `[name, from/admin, to, \"nIN:<issuer>\"]`, data the amount (i128).", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        sys.exit(0 if current == text else "docs/EVENT_SCHEMA.md is not current: run scripts/event-schema.py")
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
